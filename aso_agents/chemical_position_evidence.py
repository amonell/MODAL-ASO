"""Typed position evidence for an unambiguous supplied gapmer architecture."""

from dataclasses import replace
from aso_chemistry import gapmer_architecture


def supplied_gapmer_architecture(chemistry, sequence):
    """Read only a numeric wing-gap-wing descriptor from a chemistry field.

    A prose description with conflicting descriptors or a length mismatch is
    deliberately left uninterpreted. This does not infer chemistry from an ASO
    sequence, its target, or a narrative generated by a model.
    """
    if not isinstance(chemistry, str) or not isinstance(sequence, str):
        return None
    normalized = chemistry.lower().replace('–', '-').replace('−', '-')
    words = normalized.replace(',', ' ').replace(';', ' ').replace('(', ' ').replace(')', ' ').split()
    architectures = [parsed for word in words
                     if (parsed := gapmer_architecture(word.strip('.:'))) is not None]
    if len(architectures) != 1:
        return None
    if len(words) > 1 and ('gapmer' not in normalized or 'dna' not in normalized):
        return None
    architecture = architectures[0]
    if architecture.length != len(sequence.strip()):
        return None
    # Numeric prose supplies partition counts, not the wing chemical identity.
    # Exact canonical profiles have defined sugars; descriptive fields remain unresolved.
    return architecture if len(words) == 1 else replace(architecture, wing_chemistry="unspecified")


def chemical_position_evidence(row):
    """Map recorded 1-based positions to the supplied molecule's chemistry."""
    if not isinstance(row, dict):
        return None
    architecture = supplied_gapmer_architecture(row.get('chemistry'), row.get('sequence'))
    if architecture is None:
        return None
    partitions = {
        '5prime_wing': [1, architecture.wing_5prime],
        'dna_gap': [architecture.wing_5prime + 1,
                    architecture.wing_5prime + architecture.dna_gap],
        '3prime_wing': [architecture.wing_5prime + architecture.dna_gap + 1,
                        architecture.length],
    }
    observed = set()
    for match in row.get('near_match_candidates') or []:
        positions = match.get('mismatch_positions_in_supplied_sequence_1based')
        count = match.get('mismatch_count')
        if (not isinstance(positions, list) or not isinstance(count, int)
                or isinstance(count, bool) or count != len(positions)
                or any(not isinstance(p, int) or isinstance(p, bool)
                       or not 1 <= p <= architecture.length for p in positions)):
            continue
        observed.update(positions)
    return {
        'basis': 'Unambiguous numeric wing-gap-wing descriptor in supplied chemistry; '
                 '1-based positions refer to the supplied 5prime-to-3prime ASO sequence. '
                 'No affinity or activity is inferred.',
        'descriptor': architecture.label,
        'wing_chemistry': architecture.wing_chemistry,
        'wing_chemistry_basis': 'canonical_profile' if architecture.wing_chemistry != 'unspecified' else 'unresolved_from_numeric_partition',
        'sequence_length': architecture.length,
        'position_ranges_1based_inclusive': partitions,
        'recorded_near_match_mismatch_positions': [
            {'position_1based': p,
             'region': 'dna_gap' if architecture.in_gap(p)
                       else '5prime_wing' if p <= architecture.wing_5prime
                       else '3prime_wing'} for p in sorted(observed)],
    }
