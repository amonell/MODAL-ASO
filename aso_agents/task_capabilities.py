"""Shared executor boundaries for planning and independent plan review."""

ANNOTATION_SCOPE_CONTRACT = (
    "Keep candidate eligibility separate from annotations. mirna_binding, rbp_binding, "
    "motif_tiling and region_constraints restrict where ASOs may be designed; populate "
    "them only when the user requires candidates to target those sites. A request to "
    "annotate overlaps across a complete library, including candidates without a site, "
    "does not impose a binding-site restriction. Preserve the requested design region "
    "and library coverage, and retain the annotation requirements in a downstream "
    "analysis task and its deliverables. Do not infer an extra filter from the presence "
    "of miRNA names, mature sequences, RBP metadata or annotation input files. Mature "
    "miRNA sequences and family metadata are not transcript-specific binding-site "
    "coordinates or database-reported target predictions.\n"
)

ANALYSIS_TASK_CAPABILITIES = (ANNOTATION_SCOPE_CONTRACT +
    "Executor selection follows the canonical task_type. The native flag is derived "
    "metadata: false for sandbox_analysis and true for all other supported operations, "
    "including analyze_artifact and build_composite_report. Changing that flag does not "
    "create a different implementation or extend the operation's capabilities. Choose "
    "sandbox_analysis explicitly when a self-contained calculation is needed. "
    "Analysis executor contract: sandbox_analysis executes a self-contained computation over "
    "supplied tables, sequences, scores and arithmetic rules. One such task can recompute metrics, "
    "apply ordered filters, report every failed/unknown criterion, track sequential attrition, "
    "compare groups, rank rows and write all requested exports. These are supported operations "
    "inside that executor, not missing task nodes, when the task scope and requested outputs "
    "explicitly cover them. Audit complete coverage of each requested calculation and deliverable; "
    "a vague task label alone does not establish coverage. Do not require a separate native trace "
    "node merely because the user calls a supplied-data calculation an audit or attrition trace. "
    "trace_filter_decisions natively explains an actual recorded ASO pipeline run and its stage "
    "artifacts. If the request is instead to calculate hypothetical filter outcomes from supplied "
    "rows, use sandbox_analysis and label those outcomes accordingly; never invent run history. "
    "Exact motif or miRNA seed matching under supplied sequence rules is a self-contained "
    "sandbox_analysis calculation. For annotations on newly designed ASOs, depend on the "
    "native design task and use its recorded target sequences and coordinate mappings, "
    "alongside the supplied motif or mature-miRNA sequences. Preserve all requested rows "
    "and all overlapping associations; evidence labels must distinguish calculated matches "
    "from database-reported or experimentally established binding sites. "
    "Joining already resolved target intervals to annotation intervals and counting their "
    "overlap bases is also sandbox_analysis arithmetic, including all ASO-site associations. "
    "Keep the scan, interval join and enriched exports in that analysis when they share "
    "the same inputs. Depend on the producer of the verified coordinates; do not create "
    "an extra evaluate_existing_aso_set task for an overlap join that needs no new "
    "reference mapping or biological prediction. "
    "Attach motif, mature-miRNA and annotation files through artifact_refs. "
    "provided_asos and provided_aso_files identify actual submitted ASO molecules, "
    "not target sequences or regulatory RNAs used to annotate them. "
    "evaluate_existing_aso_set assesses ASOs against biological references; it does not "
    "execute arbitrary supplied seed rules or produce custom overlap tables by itself. "
    "Target-relative sequence mapping or biological evaluation still requires the corresponding "
    "native evaluation task: supplied oligonucleotides do not make transcript-relative binding, "
    "orientation, or genomic interval assessment self-contained, even if the transcript must "
    "first be retrieved. compare_aso_sets natively compares distinct submitted physical ASO "
    "sets as well as generated sets. When its findings depend on target-relative candidate "
    "assessment, it consumes the native evaluate_existing_aso_set or design_new_asos output "
    "through an explicit graph dependency; it does not require newly designed molecules. "
    "sandbox_analysis may compare supplied numeric rows without a biological reference, "
    "but it cannot replace that native assessment-and-comparison chain. "
    "A final_outputs.source_artifact value copies that producer's existing native "
    "content (with only the supported explicit row selection); it does not compute "
    "extra annotations, statistics, comparisons or aggregates. Check every requested "
    "result against the content that operation actually produces. When additional "
    "calculations are requested, give them an executable path: an appropriate analysis "
    "task with dependencies on its inputs, or a custom requested-output transformation "
    "using kind='file' and source_artifact=null that consumes the producer's recorded "
    "artifacts. Preserve the calculation and its output requirement explicitly. "
    "A destination directory is not a completed file. Preserve explicitly requested "
    "filenames; when only a directory is requested, choose a concrete filename there "
    "or declare the directory and format so delivery resolves a producer-bound file. "
    "For each final file, trace every required result to the operation that puts it "
    "in that file. If an analysis computes new results, bind the requested enriched "
    "table/report to that analysis or a custom transformation that consumes it. "
    "Do not bind that file to the unchanged upstream design artifact and put the "
    "new results only in a separate sidecar: a dependency or a completed calculation "
    "does not modify an upstream producer's existing artifact. "
    "When sandbox_analysis depends on a completed task, execution supplies that "
    "task's recorded outputs in task_artifacts. For completed design tasks it also "
    "supplies completed_design_candidates with real selected rows, source paths "
    "and the recorded design contract. An explicit dependency and analysis scope "
    "therefore establish this input flow without a speculative artifact_refs path. "
    "Keep artifact_refs for actual supplied paths and provided_asos for molecules "
    "actually supplied by the user; do not fill either with placeholders for "
    "future generated data. No extra export task is needed merely to name these "
    "runtime-provided upstream artifacts. Native design and target-relative "
    "evaluation resolve their public biological references internally; a request "
    "to resolve a reference does not require a separate sandbox lookup task. "
    "A promise in an assumption, output label or rationale is not execution. Do not "
    "mark a native-copy output complete merely because its filename and format match. "
    "Conversely, standard native candidate fields and ordinary report exports require "
    "no extra analysis task when their existing contents meet the request. "
    "Independent design operations, actual run-history inspection and "
    "tasks consuming independently generated outputs retain explicit nodes and dependencies.\n"
)

